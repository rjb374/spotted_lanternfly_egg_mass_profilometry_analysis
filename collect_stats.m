function stats = collect_stats(filename, numEggs, heights, xProj, xPeak, yProj, yPeak, angles, area, volume)
% COLLECT_STATS Assemble summary statistics for one egg-mass sample.
%
% Inputs are the per-sample outputs from egg detection, spacing/orientation
% analysis, and area/volume calculation. The returned scalar structure is
% appended to summaryStats by Output_data.m.

    stats = struct('Filename', filename, ...
                   'NumEggs', numEggs, ...
                   'MeanHeight', mean(heights), ...
                   'MedianHeight', median(heights), ...
                   'HeightStd', std(heights), ...
                   'XSpacingMean', mean(xProj), ...
                   'XSpacingMedian', median(xProj), ...
                   'XSpacingStd', std(xProj), ...
                   'XPeakMean', mean(xPeak), ...
                   'XPeakMedian', median(xPeak), ...
                   'XPeakMode', mode(xPeak), ...
                   'YSpacingMean', mean(yProj), ...
                   'YSpacingMedian', median(yProj), ...
                   'YSpacingStd', std(yProj), ...
                   'YPeakMean', mean(yPeak), ...
                   'YPeakMedian', median(yPeak), ...
                   'YPeakMode', mode(yPeak), ...
                   'MeanAngle', mean(angles), ...
                   'MedianAngle', median(angles), ...
                   'ModeAngle', mode(angles), ...
                   'AngleStd', std(angles), ...
                   'MassArea', area, ...
                   'MassVolume', volume);
end
